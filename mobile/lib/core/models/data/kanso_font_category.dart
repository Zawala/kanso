/// The kind of a font family, as the font settings group them.
enum KansoFontCategory {
  /// A sans-serif family.
  sans,

  /// A serif family.
  serif,

  /// A monospaced family.
  mono,

  /// The device's own font, whichever it is.
  system,
}
